/**
 * Extract the most likely concept name from a choice text string.
 * Returns the first matching concept name, or null if no match.
 */
export function extractConceptFromText(text: string): string | null {
  const lower = text.toLowerCase();
  for (const [concept, keywords] of CONCEPT_KEYWORDS) {
    for (const kw of keywords) {
      if (lower.includes(kw.toLowerCase())) {
        return concept;
      }
    }
  }
  return null;
}

/**
 * Get the human-readable name for a BACB task list item.
 */
export function getTaskName(taskItem: string): string {
  return TASK_LIST_NAMES[taskItem] ?? taskItem;
}
